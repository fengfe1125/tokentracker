    private func sample() -> SessionTranscript {
        SessionTranscript(tool: "claude", sessionID: "abcdef123456", sourcePath: "/x.jsonl", status: .ok, entries: [
            TranscriptEntry(id: 0, kind: .system, text: "注入"),
            TranscriptEntry(id: 1, kind: .user, text: "写个脚本", timestamp: 0),
            TranscriptEntry(id: 2, kind: .thinking, text: "想想"),
            TranscriptEntry(id: 3, kind: .toolCall, text: "{\n  \"command\" : \"cat a.md\"\n}", toolName: "Bash", callID: "t1",
                            model: "opus"),
            TranscriptEntry(id: 4, kind: .toolCall, text: "{}", toolName: "Read", callID: "t2"),
            TranscriptEntry(id: 5, kind: .toolResult, text: "```swift\nlet a = 1\n```", toolName: "Bash", callID: "t1"),
            TranscriptEntry(id: 6, kind: .assistant, text: "完成了", model: "opus"),
        ])
    }

    func testItemsPairToolCallsAndRespectFilter() {
        let items = TranscriptItem.build(sample().entries, filter: TranscriptFilter())
        XCTAssertEqual(items.map(\.id), [1, 3, 4, 6])
        guard case .tool(let call, let result) = items[1] else { return XCTFail() }
        XCTAssertEqual(call?.id, 3)
        XCTAssertEqual(result?.id, 5)
        guard case .tool(_, let missing) = items[2] else { return XCTFail() }
        XCTAssertNil(missing)

        let all = TranscriptItem.build(sample().entries,
                                       filter: TranscriptFilter(includeTools: false, includeThinking: true, includeSystem: true))
        XCTAssertEqual(all.map(\.id), [0, 1, 2, 6])
    }

    func testMarkdownRenderHeadingsFencesAndOptions() {
        let meta = TranscriptMarkdown.Metadata(title: "写个脚本\n第二行", agentName: "Claude Code", sessionID: "abcdef123456",
                                               workspace: "/repo", models: ["opus"], exportedAt: Date(timeIntervalSince1970: 0))
        let md = TranscriptMarkdown.render(sample(), metadata: meta, formatTime: { _ in "T" })
        XCTAssertTrue(md.hasPrefix("# 写个脚本 第二行\n"))
        XCTAssertTrue(md.contains("- **工作目录**: `/repo`"))
        XCTAssertTrue(md.contains("## 👤 用户 · T"))
        XCTAssertTrue(md.contains("## 🤖 助手 · `opus`"))
        XCTAssertEqual(md.components(separatedBy: "## 🤖").count - 1, 1, "连续的助手侧条目只出一个标题")
        XCTAssertTrue(md.contains("<summary>🔧 <code>Bash</code> — cat a.md</summary>"))
        XCTAssertTrue(md.contains("````text\n```swift\nlet a = 1\n```\n````"), "围栏比内容里的反引号更长")
        XCTAssertTrue(md.contains("_（未记录结果）_"))
        XCTAssertFalse(md.contains("想想"), "默认不导出思考")
        XCTAssertFalse(md.contains("注入"))

        let full = TranscriptMarkdown.render(sample(), metadata: meta,
                                             filter: TranscriptFilter(includeTools: false, includeThinking: true, includeSystem: true))
        XCTAssertTrue(full.contains("💭 思考"))
        XCTAssertTrue(full.contains("注入"))
        XCTAssertFalse(full.contains("🔧"))
    }

    func testMarkdownClipsLongToolOutput() {
        var t = sample()
        t.entries[5].text = String(repeating: "y", count: 50)
        let md = TranscriptMarkdown.render(t, metadata: .init(title: "", agentName: "a", sessionID: "sid"),
                                           toolOutputLimit: 20)
        XCTAssertTrue(md.hasPrefix("# sid\n"))
        XCTAssertTrue(md.contains(String(repeating: "y", count: 20) + "\n```"))
        XCTAssertFalse(md.contains(String(repeating: "y", count: 21)))
        XCTAssertTrue(md.contains("仅保留前 20 个字符"))
    }

