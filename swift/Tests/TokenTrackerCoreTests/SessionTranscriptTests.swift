    func testLimitsClipTextAndKeepNewestEntries() throws {
        let tmp = try TempDir()
        var records: [[String: Any]] = []
        for i in 0..<5 {
            records.append(["type": "user", "uuid": "u\(i)", "message": ["role": "user", "content": "问题 \(i) " + String(repeating: "x", count: 50)]])
        }
        let path = try writeJSONL(tmp, "big.jsonl", records)
        let limits = SessionTranscriptReader.Limits(maxTextChars: 10, maxToolChars: 10, maxEntries: 3)
        let t = SessionTranscriptReader.load(tool: "claude", sessionID: "s", filePath: path, limits: limits)
        XCTAssertEqual(t.entries.count, 3)
        XCTAssertEqual(t.droppedEntries, 2)
        XCTAssertTrue(t.entries[0].text.hasPrefix("问题 2"))
        XCTAssertTrue(t.entries.allSatisfy { $0.clipped && $0.text.count == 10 })
    }

