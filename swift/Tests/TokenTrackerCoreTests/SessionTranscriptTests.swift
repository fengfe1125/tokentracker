    private func writeJSONL(_ tmp: TempDir, _ name: String, _ records: [[String: Any]]) throws -> String {
        let path = tmp.path(name)
        try FileManager.default.createDirectory(atPath: (path as NSString).deletingLastPathComponent,
                                                withIntermediateDirectories: true)
        let lines = try records.map {
            String(data: try JSONSerialization.data(withJSONObject: $0, options: [.sortedKeys]), encoding: .utf8)!
        }
        try (lines.joined(separator: "\n") + "\n").write(toFile: path, atomically: true, encoding: .utf8)
        return path
    }

    private func kinds(_ t: SessionTranscript) -> [TranscriptEntry.Kind] { t.entries.map(\.kind) }

